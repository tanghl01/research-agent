export function sampleScopePrompts(scopeId: string | undefined, seed: string, count = 3): string[] {
  const pool = getScopePromptPool(scopeId);
  const shuffled = [...pool].sort((left, right) => seededScore(`${seed}:${left}`) - seededScore(`${seed}:${right}`));
  return shuffled.slice(0, count);
}

export function getScopePromptPool(scopeId: string | undefined): readonly string[] {
  return scopeId ? (scopePromptPools[scopeId] ?? defaultPrompts) : defaultPrompts;
}

export function getScopePromptPoolStats(): Record<string, number> {
  return Object.fromEntries([
    ["default", defaultPrompts.length],
    ...Object.entries(scopePromptPools).map(([id, prompts]) => [id, prompts.length])
  ]);
}

export function promptRequiresAttachment(prompt: string): boolean {
  return (
    /请在发送前上传/u.test(prompt) ||
    /(?:上传|附件|随附|拖入|选择文件|导入).{0,24}(?:文件|材料|结果包|数据|图片|照片|截图|PDF|DOCX|Word|Excel|XLSX|CSV|TSV|ZIP|FASTA|STEP|STL|3MF|DXF|G-code|草图|日志)/u.test(
      prompt
    ) ||
    /(?:文件|材料包|结果包|数据包|图片|照片|截图|PDF|DOCX|Word|Excel|XLSX|CSV|TSV|ZIP|FASTA|STEP|STL|3MF|DXF|G-code|草图|日志).{0,24}(?:上传|附件|随附|拖入|选择|导入)/u.test(
      prompt
    )
  );
}

function buildPromptPool(topics: PromptTopic[], templates: PromptTemplate[]): string[] {
  const prompts = topics.flatMap((topic, topicIndex) => templates.map((template) => template(topic, topicIndex)));
  const uniquePrompts = [...new Set(prompts)];
  if (uniquePrompts.length < TARGET_PROMPTS_PER_POOL) {
    throw new Error(`Scope prompt pool must contain at least ${TARGET_PROMPTS_PER_POOL} unique prompts.`);
  }
  return uniquePrompts.slice(0, TARGET_PROMPTS_PER_POOL);
}

function seededScore(value: string): number {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}
